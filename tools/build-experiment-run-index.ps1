[CmdletBinding()]
param([string]$RunDirectory, [string]$OutputPath)
$ErrorActionPreference = 'Stop'
$repoRoot = Split-Path -Parent $PSScriptRoot
if (-not $RunDirectory) { $RunDirectory = Join-Path $repoRoot 'experiment-runs/records' }
if (-not $OutputPath) { $OutputPath = Join-Path $repoRoot 'experiment-runs/index.md' }

function Sort-Ordinal([object[]]$Values) {
    $items = [string[]]@($Values | ForEach-Object { [string]$_ })
    [Array]::Sort($items, [StringComparer]::Ordinal)
    return $items
}

$records = [Collections.Generic.List[object]]::new()
foreach ($name in (Sort-Ordinal @(Get-ChildItem -LiteralPath $RunDirectory -Filter '*.yaml' -File | ForEach-Object Name))) {
    $file = Join-Path $RunDirectory $name; $data = [ordered]@{}
    foreach ($line in [IO.File]::ReadAllLines($file)) {
        if ($line -notmatch '^(?<key>[a-z_]+): (?<value>.+)$') { throw "Malformed experiment-run line in ${name}: $line" }
        $data[$Matches.key] = $Matches.value | ConvertFrom-Json -NoEnumerate
    }
    $records.Add([pscustomobject]$data)
}
if (-not $records.Count) { throw 'No experiment-run records found.' }

$lines = [Collections.Generic.List[string]]::new()
$lines.Add('# AudioMuse Experiment Run Index'); $lines.Add('')
$lines.Add('This file is generated by `tools/build-experiment-run-index.ps1`. Edit records in `experiment-runs/records/`, not this projection.')
$lines.Add(''); $lines.Add("Experiment runs: $($records.Count)")
$lines.Add(''); $lines.Add('## By Experiment')
foreach ($experimentId in (Sort-Ordinal @($records.experiment_id | Select-Object -Unique))) {
    $members = @($records | Where-Object experiment_id -eq $experimentId)
    $ids = Sort-Ordinal @($members.id)
    $lines.Add(''); $lines.Add("### ``$experimentId`` — $($ids.Count) runs"); $lines.Add('')
    foreach ($id in $ids) { $record = $records | Where-Object id -eq $id | Select-Object -First 1; $date = if ($null -eq $record.run_date) { 'not performed' } else { $record.run_date }; $lines.Add("- ``$id`` — ``$($record.status)`` — $date") }
}
$lines.Add(''); $lines.Add('## By Status')
foreach ($status in (Sort-Ordinal @($records.status | Select-Object -Unique))) {
    $ids = Sort-Ordinal @($records | Where-Object status -eq $status | ForEach-Object id)
    $lines.Add(''); $lines.Add("### ``$status`` — $($ids.Count) runs"); $lines.Add('')
    foreach ($id in $ids) { $record = $records | Where-Object id -eq $id | Select-Object -First 1; $lines.Add("- ``$id`` — ``$($record.experiment_id)``") }
}
[IO.File]::WriteAllText($OutputPath, (($lines -join "`n") + "`n"), [Text.UTF8Encoding]::new($false))
Write-Output "Generated experiment-run index from $($records.Count) records."
